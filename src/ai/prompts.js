/**
 * 提示词。
 *
 * 两条独立的链路：
 *   提取 —— 视觉模型看图，输出纯文本（不走 JSON，可流式，失败面更小）
 *   分析 —— 文本模型读转录结果，输出 JSON（要结构化字段）
 */

