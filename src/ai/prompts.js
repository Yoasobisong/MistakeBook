/* ============================================================
   三、按自然语言指令订正转录结果
   ============================================================ */

/**
 * 视觉模型认错公式是常态（\sqrt[n]{} 看成 n^r、指数看错一位）。
 * 重新提取未必更准 —— 同一张图它往往错在同一处；
 * 而人一眼就知道错在哪，只是懒得手打一长串 LaTeX。
 * 所以这条链路是：人说哪儿错了 → 模型改 → 人确认。
 *
 * 提示词的重点全在「别动其它地方」：让模型输出完整文本时，
 * 它很容易顺手把没让它改的部分也重写一遍。
 */
export const REVISE_SYS = `你是数学题目转录稿的校对助手。
用户会给你一段已经转录出来的文本，和一句「哪里错了」的说明。
你按说明改正，然后输出**完整的修改后文本**。

规则：
1. **只改用户指出的地方**。其余部分一个字都不要动 —— 题号、标点、换行、
   空格、大小写、LaTeX 的写法全部原样保留。这条最重要。
2. 数学式子继续用 LaTeX，行内 $...$，独立成行 $$...$$，与原文风格一致。
3. 直接输出修改后的完整文本。不要写「修改如下」之类的开场白，
   不要解释你改了什么，不要加代码围栏，也不要只输出改动的那一小段。
4. 如果看不懂用户的说明，或者原文里找不到对应的位置，
   就原样输出原文 —— 宁可不改，也不要猜着改。`

export const reviseUser = (text, instruction) =>
  `【当前转录文本】\n${text}\n\n【哪里错了】\n${instruction}\n\n请输出修改后的完整文本。`

/* ============================================================
   四、就题目与 AI 对话
   ============================================================ */

export const CHAT_SYS = `你是一位耐心的考研数学名师(985高校数学教授)，正在和学生讨论他错题本里的一道题。

要求：
- 回答紧扣这道题，不要泛泛而谈。
- 数学式子用 LaTeX：行内 $...$，独立成行 $$...$$。
- 学生问「为什么」时，讲清推理链条，不要只给结论。
- 学生思路错了要直接指出错在哪一步，不要含糊其辞。
- 简洁。能三句说清就不要写十句。`

export function chatContext({ latex, topics }) {
  const parts = ['【这道题】\n' + (latex.q || '（题干还没有转录出文字）')]
  if (latex.a) parts.push('\n【标准解析】\n' + latex.a)
  if (latex.x) parts.push('\n【补充材料】\n' + latex.x)
  if (topics?.length) parts.push('\n【已标注的考点】\n' + topics.join('、'))
  return parts.join('\n')
}

/** 章节树压成带 id 的缩进文本，让模型直接返回 id，省掉名称模糊匹配那一步 */
const chapterLines = chapters =>
  chapters.length
    ? chapters.map(({ c, depth }) => `${'  '.repeat(depth)}- ${c.id} : ${c.title}`).join('\n')
    : '（这本书还没有建章节）'

export function analyzeUser({ book, chapters, knownTopics, latex, note }) {
  const parts = []

  parts.push(`【教材】${book || '未命名'}`)
  parts.push(`\n【本书章节（格式 id : 标题）】\n${chapterLines(chapters)}`)
  parts.push(`\n【本书已有考点，含义相同必须复用】\n${knownTopics.length ? knownTopics.join('、') : '（还没有，这是第一道题）'}`)

  parts.push(`\n【题目】\n${latex.q || '（题干还没有转录出文字）'}`)
  if (latex.a) parts.push(`\n【答案解析】\n${latex.a}`)
  if (latex.x) parts.push(`\n【补充材料】\n${latex.x}`)
  if (note) parts.push(`\n【学生已写的批注，可作为判断线索】\n${note}`)

  parts.push('\n请按系统提示的 JSON 结构输出。')
  return parts.join('\n')
}
